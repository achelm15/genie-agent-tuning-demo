"""Write resources/agents/*.genie_space.yml from the agent configs in genie_demo.py.

Run it after changing anything in genie_demo.py that an agent uses:

    python3 scripts/build_agent_resources.py

The catalog, schemas and season are written as bundle variables, so the same files
deploy to any workspace. They have to be inline YAML: the bundle doesn't substitute
variables in a .geniespace.json file loaded through file_path.
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import genie_demo as g  # noqa: E402

OUT = ROOT / "resources" / "agents"
KEYS = {0: "r0_raw_tables", 1: "r1_data_levers", 2: "r2_metric_views", 3: "r3_examples_and_rules"}
# The team fields as bundle variables, for example ${var.team.short_name}.
TEAM = {k: f"${{var.team.{k}}}" for k in g.TEAM_WIDGETS}
HEADER ="# Generated by scripts/build_agent_resources.py from genie_demo.py. Don't edit by hand.\n"


def to_yaml(v, indent=0):
    """Minimal YAML emitter for the agent config: dicts, lists and JSON-quoted scalars."""
    pad = "  " * indent
    if isinstance(v, dict):
        if not v:
            return " {}"
        out = ""
        for k, x in v.items():
            out += f"\n{pad}{k}:" + to_yaml(x, indent + 1)
        return out
    if isinstance(v, list):
        if not v:
            return " []"
        out = ""
        for x in v:
            item = to_yaml(x, indent + 1)
            # Put a mapping's first key on the dash line.
            out += f"\n{pad}-" + (" " + item.lstrip() if isinstance(x, dict) else item)
        return out
    return " " + json.dumps(v, ensure_ascii=False)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for rnd, key in KEYS.items():
        schema = "${var.raw_schema}" if rnd == 0 else "${var.tuned_schema}"
        space = g.agent_config(rnd, f"${{var.catalog}}.{schema}", TEAM, "${var.season}")
        resource = {"resources": {"genie_spaces": {key: {
            "title": g.agent_title(rnd, TEAM),
            "description": g.ROUNDS[rnd][1],
            "warehouse_id": "${var.warehouse_id}",
            "parent_path": "${var.workspace_folder}",
            "serialized_space": space,
        }}}}
        path = OUT / f"{key}.genie_space.yml"
        path.write_text(HEADER + to_yaml(resource).lstrip("\n") + "\n")
        print(f"Wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
